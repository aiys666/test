def wavg_amt(rows):
    amt = sum(r[2] for r in rows)
    tr = sum(r[4] * r[2] for r in rows) / amt
    ovd = sum(r[5] * r[2] for r in rows) / amt
    return tr, ovd, amt


def wavg_draw(rows):
    draw = sum(r[3] * r[6] for r in rows)
    tr = sum(r[4] * r[3] * r[6] for r in rows) / draw
    ovd = sum(r[5] * r[3] * r[6] for r in rows) / draw
    return tr, ovd, draw


