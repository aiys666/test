def solve(rej_rows):
    rej = agg(rej_rows)
    w = rej['draw'] / base['draw']
    new_ovd = (TOT_ovd - rej['ovd'] * w) / (1 - w)
    new_tr = (TOT_tr - rej['tr'] * w) / (1 - w)
    return dict(
        rej=rej, w=w,
        keep_pen=TOT_pen - rej['pen'], keep_amt=TOT_amt - rej['amt'],
        new_tr=new_tr, new_ovd=new_ovd,
    )


def pct(x):
    return f"{x*100:.2f}%"


lines = []
