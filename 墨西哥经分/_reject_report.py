# 整体权威基线（整体数据 R5 总计）
TOT_pen, TOT_amt, TOT_tr, TOT_ovd = 38230, 55390146.63, 0.2950, 0.3234


def agg(rows):
    pen = sum(r[1] for r in rows)
    amt = sum(r[2] for r in rows)
    draw = sum(r[3] * r[6] for r in rows)
    tr = sum(r[4] * r[3] * r[6] for r in rows) / draw if draw else 0.0
    ovd = sum(r[5] * r[3] * r[6] for r in rows) / draw if draw else 0.0
    return dict(pen=pen, amt=amt, draw=draw, tr=tr, ovd=ovd)


all_rows = V6 + V5
base = agg(all_rows)

# 方案列表：(名称, 尾端行)
